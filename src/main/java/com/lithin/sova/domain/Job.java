package com.lithin.sova.domain;

import jakarta.persistence.*;
import java.time.Instant;
import java.util.UUID;

@Entity
@Table(name = "jobs")
public class Job {

    @Id
    @GeneratedValue(strategy = GenerationType.UUID) // generated by Hibernate in the app, before INSERT
    private UUID id;

    @Column(nullable = false)
    private String type;

    @Column(columnDefinition = "text")
    private String payload;

    @Enumerated(EnumType.STRING) // store the name, not the ordinal: reordering the enum must not corrupt data
    @Column(nullable = false)
    private JobStatus status;

    @Column(nullable = false)
    private int attempts;

    @Column(name = "max_attempts", nullable = false)
    private int maxAttempts;

    @Column(nullable = false)
    private int priority;

    @Column(name = "scheduled_at")
    private Instant scheduledAt;

    @Column(name = "next_retry_at")
    private Instant nextRetryAt;

    @Column(name = "claimed_by")
    private String claimedBy;

    @Column(name = "claimed_at")
    private Instant claimedAt;

    @Column(name = "idempotency_key", length = 128)
    private String idempotencyKey;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    protected Job() {} // required by JPA

    public Job(String type, String payload, int priority, int maxAttempts, Instant scheduledAt) {
        this(type, payload, priority, maxAttempts, scheduledAt, null);
    }

    public Job(String type, String payload, int priority, int maxAttempts, Instant scheduledAt, String idempotencyKey) {
        this.type = type;
        this.payload = payload;
        this.priority = priority;
        this.maxAttempts = maxAttempts;
        this.scheduledAt = scheduledAt;
        this.idempotencyKey = (idempotencyKey == null || idempotencyKey.isBlank()) ? null : idempotencyKey.trim();
        this.status = JobStatus.PENDING;
        this.attempts = 0;
    }

    @PrePersist
    void onCreate() {
        Instant now = Instant.now();
        this.createdAt = now;
        this.updatedAt = now;
    }

    @PreUpdate
    void onUpdate() {
        this.updatedAt = Instant.now();
    }

    public void markRunning() {
        if (this.status != JobStatus.CLAIMED) {
            throw new IllegalStateException("Cannot transition to RUNNING from " + this.status);
        }
        this.status = JobStatus.RUNNING;
    }

    public void markSucceeded() {
        if (this.status != JobStatus.RUNNING) {
            throw new IllegalStateException("Cannot transition to SUCCEEDED from " + this.status);
        }
        this.status = JobStatus.SUCCEEDED;
        this.claimedBy = null;
        this.claimedAt = null;
        this.nextRetryAt = null;
    }

    public void recordFailure(Instant now, long baseDelaySeconds, long maxDelaySeconds, long jitterSeconds) {
        if (this.status != JobStatus.RUNNING && this.status != JobStatus.CLAIMED) {
            throw new IllegalStateException("Cannot record failure from " + this.status);
        }
        this.attempts++;
        this.claimedBy = null;
        this.claimedAt = null;
        if (this.attempts >= this.maxAttempts) {
            this.status = JobStatus.DEAD;
            this.nextRetryAt = null;
            return;
        }
        long expMultiplier = 1L << Math.min(this.attempts - 1, 20);
        long delay = Math.min(maxDelaySeconds, baseDelaySeconds * expMultiplier) + Math.max(0L, jitterSeconds);
        this.status = JobStatus.PENDING;
        this.nextRetryAt = now.plusSeconds(delay);
    }

    public void requeueFromCrash() {
        if (this.status != JobStatus.CLAIMED && this.status != JobStatus.RUNNING) {
            throw new IllegalStateException("Cannot requeue stale job from " + this.status);
        }
        this.attempts++;
        this.claimedBy = null;
        this.claimedAt = null;
        if (this.attempts >= this.maxAttempts) {
            this.status = JobStatus.DEAD;
            this.nextRetryAt = null;
        } else {
            this.status = JobStatus.PENDING;
            this.nextRetryAt = null;
        }
    }

    public void replay() {
        if (this.status != JobStatus.DEAD) {
            throw new IllegalStateException("Only DEAD jobs can be replayed; current status is " + this.status);
        }
        this.status = JobStatus.PENDING;
        this.attempts = 0;
        this.nextRetryAt = null;
        this.claimedBy = null;
        this.claimedAt = null;
    }

    public UUID getId() { return id; }
    public String getType() { return type; }
    public String getPayload() { return payload; }
    public JobStatus getStatus() { return status; }
    public int getAttempts() { return attempts; }
    public int getMaxAttempts() { return maxAttempts; }
    public int getPriority() { return priority; }
    public Instant getScheduledAt() { return scheduledAt; }
    public Instant getNextRetryAt() { return nextRetryAt; }
    public String getClaimedBy() { return claimedBy; }
    public Instant getClaimedAt() { return claimedAt; }
    public String getIdempotencyKey() { return idempotencyKey; }
    public Instant getCreatedAt() { return createdAt; }
    public Instant getUpdatedAt() { return updatedAt; }
}
